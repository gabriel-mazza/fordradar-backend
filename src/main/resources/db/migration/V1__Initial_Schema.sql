CREATE TABLE users (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(100 CHAR) NOT NULL,
    email VARCHAR2(100 CHAR) UNIQUE NOT NULL,
    password VARCHAR2(255 CHAR) NOT NULL,
    role VARCHAR2(20 CHAR) NOT NULL,
    active NUMBER(1) DEFAULT 1 NOT NULL
);

CREATE TABLE competitor_vehicles (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand VARCHAR2(100 CHAR) NOT NULL,
    model VARCHAR2(100 CHAR) NOT NULL,
    version VARCHAR2(100 CHAR) NOT NULL,
    technical_spec CLOB,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE customer_predictions (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vin VARCHAR2(17 CHAR) UNIQUE NOT NULL,
    customer_name VARCHAR2(150 CHAR),
    customer_email VARCHAR2(100 CHAR),
    phone VARCHAR2(20 CHAR),
    retention_score NUMBER(5,2),
    prediction_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);
